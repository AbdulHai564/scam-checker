"""Train and evaluate the offline classifier. Input files stay outside the repository."""

import argparse
import csv
import hashlib
import io
import json
import math
import random
import re
import unicodedata
import zipfile
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TOKEN = re.compile(r"https?://\S+|\bwww\.\S+|[a-z]+|[0-9]+")
SEED = 411


def words(text):
    text = unicodedata.normalize("NFKC", text)
    text = re.sub(r"[A-Z]", lambda match: match[0].lower(), text)
    terms = []
    for term in TOKEN.findall(text):
        if term.startswith(("http://", "https://", "www.")):
            terms.append("_link")
        elif term.isdigit():
            terms.append("_number")
        elif len(term) <= 24:
            terms.append(term)
    return terms


def features(terms):
    return set(terms) | {f"{a} {b}" for a, b in zip(terms, terms[1:])}


def read_samples(mendeley_path, imc_path, smishx_path):
    with smishx_path.open(encoding="utf-8-sig", newline="") as file:
        for row in csv.DictReader(file):
            if row["label"] in {"legitimate", "smishing"}:
                yield row["SMS"], int(row["label"] == "smishing"), "SmishX"

    with zipfile.ZipFile(mendeley_path) as archive:
        source = archive.read("Dataset_5971.csv").decode("utf-8-sig", errors="replace")
    for row in csv.DictReader(io.StringIO(source)):
        label = row["LABEL"].strip().lower()
        if label in {"ham", "smishing"}:
            yield row["TEXT"], int(label == "smishing"), "Mendeley"

    with imc_path.open(encoding="utf-8-sig", newline="") as file:
        for row in csv.DictReader(file):
            if row["language"] == "English" and row["scam_type"] not in {"", "spam"}:
                yield row["text"], 1, "IMC"


def partition(samples):
    groups = [{}, {}, {}]
    unique = {}
    conflicts = set()
    for text, label, source in samples:
        terms = tuple(words(text))
        if not terms:
            continue
        if terms in unique and unique[terms][0] != label:
            conflicts.add(terms)
        unique.setdefault(terms, (label, source, text))

    for terms, (label, source, text) in unique.items():
        if terms in conflicts:
            continue
        # Keep messages sharing a normalized opening in the same split.
        opening = " ".join(terms[:4]).encode()
        bucket = int.from_bytes(hashlib.sha256(opening).digest()[:4], "big") % 100
        split = 0 if bucket < 70 else 1 if bucket < 85 else 2
        group = groups[split].setdefault(opening, [])
        if len(group) < 12:
            group.append((features(terms), label, source, text))
    return [[row for group in split.values() for row in group] for split in groups]


def train(examples):
    counts = Counter(term for terms, _, _, _ in examples for term in terms)
    vocabulary = sorted(term for term, count in counts.items() if count >= 5)
    indices = {term: index for index, term in enumerate(vocabulary)}
    weights = [0.0] * len(vocabulary)
    rows = [(sorted(indices[term] for term in terms if term in indices), label)
            for terms, label, _, _ in examples]
    rng = random.Random(SEED)
    bias = 0.0
    class_counts = Counter(label for _, label in rows)

    for epoch in range(16):
        rng.shuffle(rows)
        rate = 0.25 / math.sqrt(epoch + 1)
        for active, label in rows:
            scale = math.sqrt(max(1, len(active)))
            score = bias + sum(weights[i] for i in active) / scale
            prediction = 1 / (1 + math.exp(-max(-30, min(30, score))))
            update = rate * (label - prediction) * len(rows) / (2 * class_counts[label])
            bias += update
            for i in active:
                weights[i] += update / scale - rate * 0.001 * weights[i]

    # Round the deployed weights before measuring the deployed model.
    return round(bias, 5), {term: round(weight, 5) for term, weight in zip(vocabulary, weights)}


def scored(examples, bias, weights):
    for terms, label, source, _ in examples:
        known = sorted(terms & weights.keys())
        evidence = len(known)
        score = bias + sum(weights[term] for term in known) / math.sqrt(max(1, evidence))
        yield score, evidence, label, source


def measure(rows, threshold):
    positives = [(score, known) for score, known, label, _ in rows if label]
    negatives = [(score, known) for score, known, label, _ in rows if not label]
    hits = sum(known >= 4 and score >= threshold for score, known in positives)
    false_alarms = sum(known >= 4 and score >= threshold for score, known in negatives)
    return hits, len(positives), false_alarms, len(negatives)


def write_header(path, bias, weights, threshold):
    with path.open("w", encoding="ascii", newline="\n") as file:
        file.write("// Generated by tools/train_message_model.py.\n")
        file.write("namespace scam::model {\n")
        file.write(f"constexpr double bias = {bias:.5f};\n")
        file.write(f"constexpr double threshold = {threshold:.5f};\n")
        file.write("constexpr struct FeatureWeight { std::string_view text; double weight; } weights[]{\n")
        for term, weight in weights.items():
            file.write(f'    {{"{term}", {weight:.5f}}},\n')
        file.write("};\n}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mendeley_zip", type=Path)
    parser.add_argument("imc_csv", type=Path)
    parser.add_argument("smishx_csv", type=Path)
    parser.add_argument("--test-output", type=Path, help="Optional private JSON file for end-to-end evaluation")
    args = parser.parse_args()
    training, validation, test = partition(read_samples(args.mendeley_zip, args.imc_csv, args.smishx_csv))
    legitimate = (ROOT / "tools/legitimate-examples.txt").read_text(encoding="utf-8").splitlines()
    supplemental = [(features(words(text)), 0, "authored", text) for text in legitimate if text]
    public_notifications = [row for row in training if row[2] == "SmishX" and row[1] == 0]
    bias, weights = train(training + public_notifications * 3 + supplemental * 14)
    validation_scores = list(scored(validation, bias, weights))
    for threshold in (i / 20 for i in range(-60, 101)):
        _, _, false_alarms, negatives = measure(validation_scores, threshold)
        if false_alarms / negatives <= 0.04:
            break
    else:
        raise RuntimeError("Could not find a threshold within the false alarm budget")

    write_header(ROOT / "message_model.h", bias, weights, threshold)
    if args.test_output:
        args.test_output.write_text(
            json.dumps([(text, label) for _, label, _, text in test]), encoding="utf-8")
    print(f"Training: {len(training)} messages; {len(weights)} features; threshold: {threshold}")
    for name, rows in (("Validation", validation_scores), ("Held-out test", list(scored(test, bias, weights)))):
        hits, positives, false_alarms, negatives = measure(rows, threshold)
        print(f"{name}: detected {hits}/{positives} scams; flagged {false_alarms}/{negatives} legitimate messages.")
        modern = [row for row in rows if row[3] == "SmishX"]
        hits, positives, false_alarms, negatives = measure(modern, threshold)
        print(f"{name} SmishX subset: detected {hits}/{positives} scams; flagged {false_alarms}/{negatives} legitimate messages.")


if __name__ == "__main__":
    main()
